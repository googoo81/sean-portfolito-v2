function numberedSlides(
  dir: string,
  count: number,
  altPrefix: string,
): ProjectImage[] {
  return Array.from({ length: count }, (_, index) => {
    const n = String(index + 1).padStart(2, "0");
    return {
      src: `${dir}/${n}.png`,
      alt: `${altPrefix} ${index + 1}`,
    };
  });
}

